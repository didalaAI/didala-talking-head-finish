import React from 'react';
import {RememberRoom,RequestParcel,ReadingWindow,GrowingHistory,LimitedWindow,RecapReading} from './ExplainScenes';
import {EditingRequest,Workload,ModelWindow,HandoffEditor,ResumeEditor,CompressionDesk,RecapHandoff,FreshWorkspace} from './WorkScenes';
import {ScreenScene} from './ScreenScene';
export const Remade=({id}:{id:string})=>{
 if(id==='RequirementsUI')return <EditingRequest/>;
 if(id==='WaitingUI')return <EditingRequest waiting/>;
 if(id==='Definition')return <ReadingWindow/>;
 if(id==='NewWindow')return <RememberRoom/>;
 if(id==='RoundPacket')return <RequestParcel/>;
 if(id==='HistoryResend')return <RequestParcel resend/>;
 if(id==='HistoryStack')return <GrowingHistory/>;
 if(['FiniteIntro','OverflowA','RecapCapacity'].includes(id))return <LimitedWindow id={id}/>;
 if(id==='Screenshots')return <ScreenScene/>;
 if(['GaugeIntro','LoadEngine','TokenCost'].includes(id))return <Workload id={id}/>;
 if(id==='ModelCapacity')return <ModelWindow/>;
 if(id==='HandoffRequest')return <HandoffEditor request/>;
 if(id==='HandoffPack')return <HandoffEditor/>;
 if(id==='ResumeWork')return <ResumeEditor/>;
 if(id==='CompressFold')return <CompressionDesk/>;
 if(id==='CompressionResult')return <CompressionDesk result/>;
 if(id==='RecapRead')return <RecapReading/>;
 if(id==='RecapHandoff')return <RecapHandoff/>;
 if(id==='FreshPaperDesk')return <FreshWorkspace/>;
 throw Error('Unmapped V4 scene '+id);
};
